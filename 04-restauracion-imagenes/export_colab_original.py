import cv2
import matplotlib.pyplot as plt
import numpy as np
import scipy.ndimage as ndi

def filtro_contra_armonica(A,Q):

    try:
        #validamos que el denominador no sea cero
        den = (A**Q).sum()
    except:
        den = 0

    return (A**(Q+1)).sum()/den

